COMMENT ON TABLE public.react_staff_applications IS
  'REACT Studio staff pool applications from companies, teams, and individuals.';
COMMENT ON TABLE public.react_staff_skill_entries IS
  'Detailed skill evidence for staff pool filtering, such as gimbal, jimmy jib, OAP, live streaming, and subtitle design.';
COMMENT ON TABLE public.react_staff_rate_cards IS
  'Applicant-provided rate cards by skill and unit, used for rough filtering only.';
